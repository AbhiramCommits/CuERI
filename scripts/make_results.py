#!/usr/bin/env python3
"""Assemble every results CSV into results/RESULTS.md.

No number is typed by hand: every value is read from a CSV or JSON produced by
an earlier script in this repository.  Missing measurements are carried through
verbatim as "not measured (no GPU on build machine)".
"""
from __future__ import annotations

import csv
import glob
import json
import os


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def fmt(x, nd=3):
    try:
        return f"{float(x):.{nd}e}"
    except (TypeError, ValueError):
        return str(x)


def main() -> int:
    env = json.load(open("results/environment.json", encoding="utf-8"))
    lines = []
    A = lines.append

    A("# cuERI measurement report")
    A("")
    A(f"Generated by `scripts/make_results.py` from the CSVs in `results/`.")
    A("")
    A(f"**Hardware tier: {env['tier']}** - {env['tier_text']}  ")
    A(f"Platform: {env['platform']}  ")
    A(f"CPU: {env['cpu_model']} ({env['cpu_logical_cores']} logical cores)  ")
    A(f"Compiler: {env['compiler_cxx']}  ")
    A(f"nvcc: {env['nvcc_version']}  ")
    A(f"GPU: {env['gpu_model']}")
    A("")
    A("Cells that could not be measured say \"not measured (no GPU on build machine)\". "
      "Every other number in this file comes from a CSV or JSON in `results/`.")
    A("")

    # ---------------- accuracy: one electron ----------------
    rows = read_csv("results/accuracy_one_electron.csv")
    if rows:
        A("## One-electron integrals vs PySCF/libcint")
        A("")
        A(f"Reference: {rows[0]['reference_source']}. Relative errors use the "
          f"stated floor ({rows[0]['rel_floor']}); `scaled` is the maximum absolute error "
          "divided by the largest reference element in the class.")
        A("")
        A("| precision | shell class | max rel error | max scaled error | worst case |")
        A("|---|---|---|---|---|")
        for prec in ("fp64", "fp32"):
            classes = sorted({r["shell_class"] for r in rows if r["precision"] == prec})
            for cls in classes:
                sub = [r for r in rows if r["precision"] == prec and r["shell_class"] == cls]
                w = max(sub, key=lambda r: float(r["max_rel_error"]))
                A(f"| {prec} | {cls} | {fmt(w['max_rel_error'])} | "
                  f"{fmt(w['max_scaled_error'])} | {w['molecule']}/{w['basis']} ({w['matrix']}) |")
        A("")

    # ---------------- accuracy: ERI ----------------
    rows = read_csv("results/accuracy_eri.csv")
    if rows:
        A("## Two-electron integrals vs PySCF/libcint")
        A("")
        A(f"Reference: {rows[0]['reference_source']}. Scaling as above; classes are "
          "`bra-pair-ket-pair` where each pair is the unordered angular-momentum pair.")
        A("")
        A("| precision | shell class | max rel error | max scaled error | worst case |")
        A("|---|---|---|---|---|")
        for prec in ("fp64", "fp32"):
            classes = sorted({r["shell_class"] for r in rows if r["precision"] == prec})
            for cls in classes:
                sub = [r for r in rows if r["precision"] == prec and r["shell_class"] == cls]
                w = max(sub, key=lambda r: float(r["max_scaled_error"]))
                A(f"| {prec} | {cls} | {fmt(w['max_rel_error'])} | "
                  f"{fmt(w['max_scaled_error'])} | {w['molecule']}/{w['basis']} |")
        A("")

    # ---------------- RHF ----------------
    rows = read_csv("results/rhf_closed_loop.csv")
    if rows:
        A("## RHF closed loop (cuERI integrals only)")
        A("")
        A("| molecule | basis | nbf | electrons | SCF iterations | E(cuERI) / Ha | "
          "E(PySCF) / Ha | abs delta / Ha |")
        A("|---|---|---|---|---|---|---|---|")
        for r in rows:
            A(f"| {r['molecule']} | {r['basis']} | {r['nbf']} | {r['n_elec']} | {r['n_iter']} | "
              f"{float(r['e_cueri']):.12f} | {float(r['e_pyscf']):.12f} | "
              f"{fmt(r['abs_delta_hartree'])} |")
        A("")

    # ---------------- Boys ----------------
    rows = read_csv("results/boys_corner_cases.csv")
    if rows:
        worst = max(rows, key=lambda r: float(r["rel_error"]))
        by_branch = {}
        for r in rows:
            b = r["branch"]
            v = float(r["rel_error"])
            by_branch[b] = max(by_branch.get(b, 0.0), v)
        A("## Boys function corner cases")
        A("")
        A(f"{len(rows)} values over T = 1e-16 .. 1e3 and n = 0..12, compared with SciPy.")
        A("")
        A(f"- worst relative error: {fmt(worst['rel_error'])} at T = {worst['T']}, "
          f"n = {worst['n']}, branch `{worst['branch']}`")
        for b, v in sorted(by_branch.items()):
            A(f"- branch `{b}`: max relative error {fmt(v)}")
        A("")
        A("![Boys corner cases](figures/boys_corner_cases.png)")
        A("")

    # ---------------- precision growth ----------------
    rows = read_csv("results/precision_error_growth.csv")
    if rows:
        A("## fp32 vs fp64 error growth")
        A("")
        A("| study | worst fp32-vs-fp64 scaled error | location | max amplification vs mildest point |")
        A("|---|---|---|---|")
        for study in sorted({r["study"] for r in rows}):
            sub = [r for r in rows if r["study"] == study]
            w = max(sub, key=lambda r: float(r["max_err_fp32_vs_fp64"]))
            amp = max(float(r["amplification_fp32_vs_baseline"]) for r in sub)
            A(f"| {study} | {fmt(w['max_err_fp32_vs_fp64'])} | {w['observable']} "
              f"{w['shell_class']} at {w['value']} | {amp:.2f}x |")
        A("")
        worst64 = max(rows, key=lambda r: float(r["max_err_fp64_vs_ref"]))
        A(f"Worst fp64-vs-PySCF scaled error in the sweep: {fmt(worst64['max_err_fp64_vs_ref'])} "
          f"({worst64['study']}, {worst64['observable']}, {worst64['shell_class']}).")
        A("")
        A("![Precision error growth](figures/precision_error_growth.png)")
        A("")

    # ---------------- screening ----------------
    rows = read_csv("results/screening.csv")
    if rows:
        A("## Schwarz screening")
        A("")
        A("| molecule | basis | tolerance | quartets | skipped | skip fraction | "
          "max deviation | within bound |")
        A("|---|---|---|---|---|---|---|---|")
        for r in rows:
            A(f"| {r['molecule']} | {r['basis']} | {r['tolerance']} | {r['quartets_total']} | "
              f"{r['quartets_screened']} | {float(r['skip_fraction']) * 100:.2f}% | "
              f"{fmt(r['max_abs_deviation'])} | {r['within_bound']} |")
        A("")

    # ---------------- benchmark ----------------
    rows = read_csv("results/benchmark.csv")
    if rows:
        measured = [r for r in rows if r["status"] == "measured"]
        A("## Benchmark")
        A("")
        A("Median wall time over three passes after one warm-up; screen tolerance 1e-10.")
        A("")
        A("| molecule | basis | nbf | ERI cpu-1thread / ms | ERI cpu-openmp / ms | speedup | "
          "integrals/s (openmp) |")
        A("|---|---|---|---|---|---|---|")
        cases = sorted({(r["molecule"], r["basis"]) for r in measured})
        for mol, bas in cases:
            def pick(backend):
                for r in measured:
                    if (r["molecule"], r["basis"], r["operation"], r["precision"],
                            r["algorithm"], r["backend"]) == (mol, bas, "eri", "fp64", "md",
                                                              backend):
                        return r
                return None
            one = pick("cpu-1thread")
            omp = pick("cpu-openmp")
            if one and omp:
                A(f"| {mol} | {bas} | {one['nbf']} | {float(one['median_ms']):.2f} | "
                  f"{float(omp['median_ms']):.2f} | {float(omp['speedup_vs_cpu1']):.2f}x | "
                  f"{float(omp['rate']):.3e} |")
        A("")
        A("MD vs Rys (cpu-openmp, fp64):")
        A("")
        A("| molecule | basis | MD / ms | Rys / ms | Rys/MD |")
        A("|---|---|---|---|---|")
        for mol, bas in cases:
            def pick2(algo):
                for r in measured:
                    if (r["molecule"], r["basis"], r["operation"], r["precision"],
                            r["algorithm"], r["backend"]) == (mol, bas, "eri", "fp64", algo,
                                                              "cpu-openmp"):
                        return r
                return None
            mdr, ryr = pick2("md"), pick2("rys")
            if mdr and ryr:
                A(f"| {mol} | {bas} | {float(mdr['median_ms']):.2f} | "
                  f"{float(ryr['median_ms']):.2f} | "
                  f"{float(ryr['median_ms']) / float(mdr['median_ms']):.2f} |")
        A("")
        cuda = [r for r in rows if r["backend"].startswith("cuda-")]
        n_meas = sum(1 for r in cuda if r["status"] == "measured")
        A(f"CUDA rows: {n_meas} measured, {len(cuda) - n_meas} not measured. "
          "Unmeasured cells read \"not measured (no GPU on build machine)\".")
        A("")

    # ---------------- occupancy ----------------
    rows = read_csv("results/occupancy.csv")
    if rows:
        A("## Registers and occupancy per angular-momentum class")
        A("")
        statuses = sorted({r["status"] for r in rows})
        A(f"Rows: {len(rows)}; statuses: {', '.join(statuses)}.")
        A("")
        if all(r["status"] == "not measured" for r in rows):
            A("| angular class | status | registers/thread | occupancy | memory throughput | "
              "SM throughput |")
            A("|---|---|---|---|---|---|")
            for r in rows:
                A(f"| {r['angular_class']} | {r['status']} | {r['registers_per_thread'] or '-'} | "
                  f"{r['occupancy_pct'] or '-'} | {r['memory_throughput_pct'] or '-'} | "
                  f"{r['sm_throughput_pct'] or '-'} |")
            A("")
            A(f"Reason: {rows[0]['note']}.")
        else:
            A("| angular class | status | registers/thread | occupancy % | spill stores | "
              "spill loads | blocks/SM |")
            A("|---|---|---|---|---|---|---|")
            for r in rows:
                A(f"| {r['angular_class']} | {r['status']} | {r['registers_per_thread']} | "
                  f"{r['occupancy_pct']} | {r['spill_stores']} | {r['spill_loads']} | "
                  f"{r['blocks_per_sm']} |")
        A("")

    A("## Generated figures")
    A("")
    for p in sorted(glob.glob("results/figures/*.png")):
        A(f"- [{p}]({os.path.relpath(p, 'results')})")
    A("")

    with open("results/RESULTS.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("[results] wrote results/RESULTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
